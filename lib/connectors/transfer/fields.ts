// lib/connectors/transfer/fields.ts
// Complete column classification for the connector transfer bundle. Every column
// of ExternalApiConnection must be assigned to exactly one list; the drift test
// (tests/connectors/transfer/schema-drift.test.ts) enforces this so a newly added
// column can never silently leak into (or drop out of) an export.

/**
 * Config columns that are safe and portable across environments. These travel in
 * the bundle verbatim (except `extraHeaders`, whose *values* are filtered — see
 * export.ts — while the field itself is a config column, not a secret column).
 */
export const CONNECTION_EXPORT_COLUMNS = [
  'name', 'slug', 'description', 'httpMethod', 'authType', 'authKeyHeader',
  'promptFieldName', 'fileFieldName', 'fileUrlFieldName', 'defaultPrompt',
  'staticFormFields', 'extraHeaders', 'responseContentPath',
  'sessionIdResponsePath', 'sessionIdFieldName', 'timeoutSec', 'state',
] as const;

/**
 * Environment-specific columns. They are exported but MUST be reviewed / remapped
 * by the operator at import time (the wizard prefills them and warns on host change).
 * `vaultSecretPath` is a logical, env-agnostic reference — portable as-is, but its
 * presence in the target Vault is a precondition, not something the bundle guarantees.
 */
export const CONNECTION_ENV_COLUMNS = [
  'endpointUrl', 'vaultSecretPath',
] as const;

/**
 * Secret columns — NEVER written to a bundle. `authSecret` is stored plaintext in
 * the DB, so it is hard-omitted at export and rejected at import (deny-list).
 */
export const CONNECTION_SECRET_COLUMNS = ['authSecret'] as const;

/** Internal identity / timestamps — never exported, regenerated by the target. */
export const CONNECTION_INTERNAL_COLUMNS = ['id', 'createdAt', 'updatedAt'] as const;

export type ConnectionExportColumn = (typeof CONNECTION_EXPORT_COLUMNS)[number];
export type ConnectionEnvColumn = (typeof CONNECTION_ENV_COLUMNS)[number];
